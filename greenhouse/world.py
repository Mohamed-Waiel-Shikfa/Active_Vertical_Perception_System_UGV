import math
from collections.abc import Sequence
from pathlib import Path
from typing import TYPE_CHECKING
from xml.etree import ElementTree as ET

from greenhouse.mesh import numbers

if TYPE_CHECKING:
    from greenhouse.config import Config

WORLD_NAME = "greenhouse"
SYSTEMS = {
    "Physics": "physics",
    "UserCommands": "user-commands",
    "SceneBroadcaster": "scene-broadcaster",
    "Sensors": "sensors",
    "Imu": "imu",
    "NavSat": "navsat",
}


def child(parent: ET.Element, tag: str, text: object | None = None, **attributes: str) -> ET.Element:
    """Append and return a ``tag`` element under ``parent``, with ``str(text)`` as its text if given."""
    node = ET.SubElement(parent, tag, attributes)
    if text is not None:
        node.text = str(text)
    return node


def write_xml(path: Path, root: ET.Element) -> None:
    """Write ``root`` as indented UTF-8 XML to ``path``, creating parent directories."""
    path.parent.mkdir(parents=True, exist_ok=True)
    ET.indent(root, space="  ")
    ET.ElementTree(root).write(path, encoding="utf-8", xml_declaration=True)


def material(parent: ET.Element, color: Sequence[float], transparency: float = 0) -> None:
    """Add an SDF material with RGBA ``color`` (0-1) to ``parent``.

    A nonzero ``transparency`` (0 opaque, 1 invisible) is set on ``parent`` itself, where SDF reads it.
    """
    node = child(parent, "material")
    child(node, "ambient", numbers(color))
    child(node, "diffuse", numbers(color))
    child(node, "specular", "0.15 0.15 0.15 1")
    if transparency:
        child(parent, "transparency", str(transparency))


def box(link: ET.Element, name: str, pose: Sequence[float], size: Sequence[float],
        color: Sequence[float], transparency: float = 0) -> None:
    """Add a matching box collision and visual to ``link``.

    ``pose`` is ``(x, y, z, roll, pitch, yaw)`` in metres/radians in the link frame; ``size`` is
    ``(x, y, z)`` metres; ``color`` RGBA 0-1. Transparent visuals do not cast shadows.
    """
    for tag in ("collision", "visual"):
        node = child(link, tag, name=f"{name}_{tag}")
        child(node, "pose", numbers(pose))
        child(child(child(node, "geometry"), "box"), "size", numbers(size))
        if tag == "visual":
            material(node, color, transparency)
            if transparency:
                child(node, "cast_shadows", "false")


def model_config(path: Path, name: str, description: str) -> None:
    """Write a Gazebo ``model.config`` for a ``model.sdf`` beside it."""
    root = ET.Element("model")
    child(root, "name", name)
    child(root, "version", "1.0")
    child(root, "sdf", "model.sdf", version="1.9")
    child(child(root, "author"), "name", "Jackal greenhouse contributors")
    child(root, "description", description)
    write_xml(path, root)


def terrain_model(directory: Path, friction_coefficient: float = 0.9) -> None:
    """Write the static ground model (``model.sdf`` + ``model.config``) into ``directory``.

    Visual and collision share ``meshes/terrain.dae`` at scale 1 (world-frame metres); the
    dimensionless ``friction_coefficient`` sets both ODE ``mu`` and ``mu2``.
    """
    root = ET.Element("sdf", version="1.9")
    model = child(root, "model", name="greenhouse_ground")
    child(model, "static", "true")
    link = child(model, "link", name="ground")
    for tag in ("collision", "visual"):
        node = child(link, tag, name=f"terrain_{tag}")
        mesh = child(child(node, "geometry"), "mesh")
        child(mesh, "uri", "model://greenhouse_ground/meshes/terrain.dae")
        child(mesh, "scale", "1 1 1")
        if tag == "visual":
            soil = child(node, "material")
            child(soil, "ambient", "0.34 0.24 0.135 1")
            child(soil, "diffuse", "1 1 1 1")
            child(soil, "specular", "0.04 0.04 0.04 1")
            child(soil, "emissive", "0 0 0 1")
            metal = child(child(soil, "pbr"), "metal")
            child(metal, "albedo_map", "model://greenhouse_ground/materials/textures/soil.png")
            child(metal, "roughness", "0.95")
            child(metal, "metalness", "0")
        else:
            friction = child(child(child(node, "surface"), "friction"), "ode")
            child(friction, "mu", str(friction_coefficient))
            child(friction, "mu2", str(friction_coefficient))
    write_xml(directory / "model.sdf", root)
    model_config(directory / "model.config", "Greenhouse soil",
                 "GPL-3.0 terrain generated by the pinned virtual_maize_field algorithm; identical visual and collision mesh.")


def plant_model(directory: Path, height: float, collision_radius: float) -> None:
    """Write the static tomato model (``model.sdf`` + ``model.config``) into ``directory``.

    Model frame: origin at the stem base, +z up. Collision is a 0.02 m stem cylinder of ``height``
    metres plus a ``collision_radius`` m canopy cylinder from 0.15 m to ``height``.
    """
    root = ET.Element("sdf", version="1.9")
    model = child(root, "model", name="greenhouse_tomato")
    child(model, "static", "true")
    link = child(model, "link", name="plant")
    visual = child(link, "visual", name="tomato")
    mesh = child(child(visual, "geometry"), "mesh")
    child(mesh, "uri", "model://greenhouse_tomato/meshes/tomato.dae")
    child(mesh, "scale", "1 1 1")
    for name, bottom, length, radius in (
        ("stem", 0, height, 0.02), ("canopy_envelope", 0.15, height - 0.15, collision_radius)
    ):
        collision = child(link, "collision", name=name)
        child(collision, "pose", numbers((0, 0, bottom + length / 2, 0, 0, 0)))
        cylinder = child(child(collision, "geometry"), "cylinder")
        child(cylinder, "radius", f"{radius:.9f}")
        child(cylinder, "length", f"{length:.9f}")
    write_xml(directory / "model.sdf", root)
    model_config(directory / "model.config", "Stylized tomato",
                 "Four resized/stacked crowns of simple plant by aaron_nerlich (CC BY 4.0), via virtual_maize_field; original stems and twelve red fruit. Adapted asset: CC BY 4.0. See THIRD_PARTY_NOTICES.md.")


def greenhouse_world(config: "Config", placements: list[dict[str, str | float]]) -> ET.Element:
    """Build the world SDF root: physics, sun, ground, one tomato per placement and the house shell.

    World frame: origin at the house centre, +x along the rows, +y across them, +z up (ENU).
    Each placement gives ``name``, ``x``/``y``/``z`` in metres and ``yaw`` in radians.
    """
    root = ET.Element("sdf", version="1.9")
    world = child(root, "world", name=WORLD_NAME)
    child(world, "gravity", "0 0 -9.81")
    physics = child(world, "physics", name="default_physics", type="ignored")
    child(physics, "max_step_size", "0.002")
    child(physics, "real_time_factor", "1")
    for system, library in SYSTEMS.items():
        plugin = child(world, "plugin", filename=f"gz-sim-{library}-system",
                       name=f"gz::sim::systems::{system}")
        if system == "Sensors":
            child(plugin, "render_engine", "ogre2")
    coordinates = child(world, "spherical_coordinates")
    child(coordinates, "surface_model", "EARTH_WGS84")
    child(coordinates, "world_frame_orientation", "ENU")
    child(coordinates, "latitude_deg", "51.99")
    child(coordinates, "longitude_deg", "5.66")
    child(coordinates, "elevation", "0")
    child(coordinates, "heading_deg", "0")
    scene = child(world, "scene")
    child(scene, "ambient", "0.65 0.65 0.65 1")
    child(scene, "background", "0.73 0.83 0.88 1")
    child(scene, "shadows", "true")
    sun = child(world, "light", name="greenhouse_sun", type="directional")
    child(sun, "pose", "0 0 12 0 0 0")
    child(sun, "diffuse", "0.85 0.83 0.75 1")
    child(sun, "specular", "0.2 0.2 0.2 1")
    child(sun, "direction", "-0.4 0.25 -0.9")
    child(sun, "cast_shadows", "true")
    attenuation = child(sun, "attenuation")
    child(attenuation, "range", "100")
    child(attenuation, "constant", "1")
    child(attenuation, "linear", "0")
    child(attenuation, "quadratic", "0")
    child(child(world, "include"), "uri", "model://greenhouse_ground")
    for placement in placements:
        include = child(world, "include")
        child(include, "uri", "model://greenhouse_tomato")
        child(include, "name", placement["name"])
        child(include, "pose", numbers((placement["x"], placement["y"], placement["z"], 0, 0, placement["yaw"])))
    shell = child(world, "model", name="greenhouse_structure")
    child(shell, "static", "true")
    link = child(shell, "link", name="frame")
    length, width, eaves = config.house_length, config.house_width, config.eaves_height
    frame_color, panel_color = (0.69, 0.73, 0.68, 1), (0.69, 0.88, 0.84, 1)
    n_bays = max(2, math.ceil(length / 3))
    for i in range(n_bays + 1):
        x = -length / 2 + length * i / n_bays
        for side in (-1, 1):
            box(link, f"post_{i}_{side}", (x, side * width / 2, (eaves - 0.1) / 2, 0, 0, 0),
                (0.08, 0.08, eaves + 0.1), frame_color)
    for side in (-1, 1):
        box(link, f"side_panel_{side}", (0, side * width / 2, eaves / 2, 0, 0, 0),
            (length, 0.025, eaves), panel_color, 0.80)
        for z in (0.08, eaves):
            box(link, f"side_rail_{side}_{z}", (0, side * width / 2, z, 0, 0, 0),
                (length, 0.08, 0.08), frame_color)
        end_span = (width - config.door_width) / 2
        for end in (-1, 1):
            box(link, f"end_panel_{end}_{side}",
                (end * length / 2, side * (width + config.door_width) / 4, eaves / 2, 0, 0, 0),
                (0.025, end_span, eaves), panel_color, 0.80)
            box(link, f"door_post_{end}_{side}",
                (end * length / 2, side * config.door_width / 2, (eaves - 0.1) / 2, 0, 0, 0),
                (0.08, 0.08, eaves + 0.1), frame_color)
        rise = config.ridge_height - eaves
        slope = math.atan2(rise, width / 2)
        box(link, f"roof_panel_{side}",
            (0, side * width / 4, (eaves + config.ridge_height) / 2, -side * slope, 0, 0),
            (length, math.hypot(width / 2, rise), 0.025), panel_color, 0.86)
        for i in range(n_bays + 1):
            x = -length / 2 + length * i / n_bays
            box(link, f"rafter_{i}_{side}",
                (x, side * width / 4, (eaves + config.ridge_height) / 2, -side * slope, 0, 0),
                (0.065, math.hypot(width / 2, rise), 0.065), frame_color)
    box(link, "ridge", (0, 0, config.ridge_height, 0, 0, 0), (length, 0.07, 0.07), frame_color)
    for end in (-1, 1):
        box(link, f"door_lintel_{end}", (end * length / 2, 0, eaves, 0, 0, 0),
            (0.08, width, 0.08), frame_color)
    return root
